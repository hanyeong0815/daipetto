-- 病院管理者とその管理対象病院の紐付け（06_ERD §11）。病院管理者は紐付いた病院だけを管理できる
CREATE TABLE hospital_admins (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT    NOT NULL,
    hospital_id BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_hospital_admins_user
        FOREIGN KEY (user_id)
            REFERENCES users (id),

    CONSTRAINT fk_hospital_admins_hospital
        FOREIGN KEY (hospital_id)
            REFERENCES hospitals (id),

    CONSTRAINT uq_hospital_admins_user_hospital
        UNIQUE (user_id, hospital_id)
);

CREATE INDEX idx_hospital_admins_hospital_id ON hospital_admins (hospital_id);
