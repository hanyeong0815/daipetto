CREATE TABLE vaccinations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id         BIGINT       NOT NULL,
    vaccine_name   VARCHAR(100) NOT NULL,
    scheduled_date DATE         NOT NULL,
    completed_date DATE         NULL,
    status         VARCHAR(30)  NOT NULL DEFAULT 'SCHEDULED',
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at     TIMESTAMP    NULL,

    CONSTRAINT fk_vaccinations_pet
        FOREIGN KEY (pet_id)
            REFERENCES pets (id)
);

CREATE INDEX idx_vaccinations_pet_id ON vaccinations (pet_id);
-- リマインダーSchedulerの抽出条件（status・接種予定日）
CREATE INDEX idx_vaccinations_status_scheduled_date ON vaccinations (status, scheduled_date);

-- V10 で列だけ作成していた notifications.vaccination_id にFK制約を追加する（06_ERD §15）
ALTER TABLE notifications
    ADD CONSTRAINT fk_notifications_vaccination
        FOREIGN KEY (vaccination_id)
            REFERENCES vaccinations (id);
